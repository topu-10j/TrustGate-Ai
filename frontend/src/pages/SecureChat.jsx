import { useEffect, useRef, useState } from "react";
import { Bot, Send, ShieldCheck, LockKeyhole, Sparkles, User, Loader2, ShieldAlert, Plus, Trash2 } from "lucide-react";
import PageHeader from "../components/PageHeader";
import StatusPill from "../components/StatusPill";
import { sendChat } from "../services/api";
import { useWorkspace } from "../state/AuthWorkspace";
const starters = [
  ["Ask office hours", "What are the office hours?"],
  ["Try budget question", "What is the confidential budget?"],
  ["Ask project deadline", "What is the project deadline?"],
];

export default function SecureChat() {
  const { role, user, sessionError, expire, refreshAudit } = useWorkspace();
  const [messages, setMessages] = useState([{ id: 0, role: "assistant", content: "Welcome to TrustGate. Ask a question about workspace documents you are authorized to access." }]);
  const [value, setValue] = useState("");
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");
  const bottom = useRef(null);
  const active = useRef(null);
  const sequence = useRef(0);
  const add = (item) => {
    const id = ++sequence.current;
    setMessages((old) => [...old, { id, ...item }]);
  };
  const newChat = () => {
    active.current?.abort();
    active.current = null;
    setLoading(false);
    setError("");
    setValue("");
    sequence.current += 1;
    setMessages([{ id: sequence.current, role: "assistant", content: "Welcome to TrustGate. Ask a question about workspace documents you are authorized to access." }]);
  };
  const clearChat = () => {
    active.current?.abort();
    active.current = null;
    setLoading(false);
    setError("");
    setValue("");
    setMessages([]);
  };

  useEffect(() => () => active.current?.abort(), []);
  useEffect(() => {
    if (messages.length > 1) bottom.current?.scrollIntoView({ block: "nearest" });
  }, [messages.length]);

  async function submit(text = value) {
    const message = text.trim();
    if (!message || !user || active.current) return;
    const request = new AbortController();
    active.current = request;
    setValue("");
    setError("");
    add({ role: "user", content: message });
    setLoading(true);
    try {
      const data = await sendChat(message, request.signal);
      if (!request.signal.aborted) add({ role: "assistant", content: data?.answer || "No answer was returned.", sources: Array.isArray(data?.sources) ? data.sources : [], decision: data?.decision || "ALLOW" });
    } catch (failure) {
      if (request.signal.aborted) return;
      if (failure.status === 401) {
        expire();
      } else if (failure.status === 403 && failure.code === "ACCESS_DENIED") {
        add({ role: "assistant", content: failure.message, decision: "DENIED", code: failure.code });
      } else if (failure.status === 403 && failure.code === "PROMPT_BLOCKED") {
        add({ role: "assistant", content: failure.message || "This prompt was blocked by TrustGate security policy.", decision: "BLOCKED", code: failure.code });
      } else if (failure.status === 429 && failure.code === "CHAT_COOLDOWN") {
        setError("Chat is temporarily paused due to a cooldown. Please wait and try again.");
      } else {
        setError(failure.message);
      }
    } finally {
      if (active.current === request) active.current = null;
      if (!request.signal.aborted && active.current === null) {
        setLoading(false);
        if (role === "admin") refreshAudit();
      }
    }
  }

 return <div className="mx-auto max-w-5xl"><PageHeader eyebrow="PROTECTED CONVERSATION" title="Secure AI Chat" description="Responses are generated by the backend and restricted to your authenticated access permissions." action={null}/><section className="panel flex min-h-[620px] flex-col overflow-hidden"><div className="flex flex-wrap items-center justify-between gap-3 border-b border-ui px-5 py-4"><div className="flex items-center gap-3"><div className="accent-soft rounded-xl p-2.5"><Bot size={21}/></div><div><h3 className="text-sm font-semibold text-main">TrustGate Assistant</h3><p className="text-[10px] text-muted">Backend-secured answers</p></div></div><div className="flex flex-wrap items-center gap-2"><div className="flex items-center gap-2 rounded-full accent-soft px-3 py-2 text-[10px] font-semibold"><ShieldCheck size={13}/> {user ? "SECURITY CHECK ENABLED" : sessionError ? "SESSION UNAVAILABLE" : "AUTHENTICATING"}</div><button type="button" onClick={newChat} className="panel-soft flex items-center gap-1.5 rounded-lg px-2.5 py-2 text-[10px] text-muted"><Plus size={13}/> New Chat</button><button type="button" onClick={clearChat} disabled={!messages.length} className="panel-soft flex items-center gap-1.5 rounded-lg px-2.5 py-2 text-[10px] text-muted disabled:opacity-40"><Trash2 size={13}/> Clear</button></div></div>
 <div className="flex-1 space-y-4 overflow-y-auto p-4 md:p-6" aria-label="Chat messages" aria-live="polite">{messages.map(m=><div key={m.id} className={`flex gap-3 ${m.role==="user"?"flex-row-reverse":""}`}><div className={`flex h-9 w-9 shrink-0 items-center justify-center rounded-xl ${m.role==="user"?"accent-soft":"accent-soft"}`}>{m.role==="user"?<User size={17}/>:<Bot size={18}/>}</div><div role={m.decision === "DENIED" || m.decision === "BLOCKED" ? "alert" : undefined} className={`max-w-[85%] rounded-2xl p-4 ${m.role==="user"?"accent-soft":"panel-soft"}`}>{(m.decision === "DENIED" || m.decision === "BLOCKED") && <p className="mb-1 text-sm font-bold text-red-400">{m.decision === "BLOCKED" ? "Prompt Blocked" : "Access Denied"}</p>}<p className="whitespace-pre-wrap break-words text-sm leading-6 text-main">{m.content}</p>{m.decision&&<div className="mt-3 flex flex-wrap items-center gap-2"><StatusPill value={m.decision}/>{m.code && <span className="text-[10px] text-red-400">{m.code}</span>}{m.risk_level&&<StatusPill value={m.risk_level}/>}{Number.isFinite(m.risk_score)&&<span className="text-[10px] text-muted">Risk {m.risk_score}/100</span>}{m.mode&&<span className="text-[9px] text-subtle">{m.mode}</span>}</div>}{m.sources?.length>0&&<div className="mt-3 border-t border-ui pt-2"><p className="mb-1 text-[10px] font-semibold text-muted">Sources</p><ul className="space-y-1">{m.sources.map(source=><li key={source.id||source.title} className="text-[10px] text-muted">{source.title||source.id}</li>)}</ul></div>}{m.threats?.length>0&&<p className="mt-2 flex items-center gap-1 text-[10px] text-orange-400"><ShieldAlert size={12}/>{m.threats.join(", ")}</p>}</div></div>)}{loading&&<div className="flex items-center gap-3"><div className="accent-soft rounded-xl p-2"><Bot size={18}/></div><div className="panel-soft flex items-center gap-2 rounded-xl px-4 py-3 text-xs text-muted"><Loader2 size={14} className="animate-spin"/>Checking request…</div></div>}<div ref={bottom}/></div>
 <div className="flex flex-wrap gap-2 px-5 pb-3">{starters.map(([label,prompt])=><button key={label} type="button" disabled={!user || loading} onClick={()=>submit(prompt)} className="rounded-full border border-ui px-3 py-2 text-[10px] text-muted hover:border-[var(--accent)] disabled:opacity-40">{label}</button>)}</div>
 {(sessionError || error) && <p role="alert" className="px-5 pb-2 text-xs text-red-400">{sessionError || error} {}</p>}
 <form onSubmit={e=>{e.preventDefault();submit()}} className="border-t border-ui p-4"><div className="flex items-end gap-2 rounded-2xl border border-ui bg-[var(--input)] p-2"><textarea aria-label="Message" maxLength={500} rows={1} value={value} onChange={e=>setValue(e.target.value)} onKeyDown={e=>{if(e.key==="Enter"&&!e.shiftKey&&!e.nativeEvent.isComposing){e.preventDefault();submit()}}} placeholder="Ask a secure workspace question… (Enter to send)" className="max-h-32 min-w-0 flex-1 resize-y bg-transparent px-3 py-2 text-xs text-main outline-none placeholder:text-subtle"/><button type="submit" disabled={!user||!value.trim()||loading} aria-label="Send message" className="accent-bg rounded-xl p-3 disabled:opacity-40"><Send size={16}/></button></div><p className="mt-2 text-center text-[9px] text-subtle"><LockKeyhole size={10} className="mr-1 inline"/>The backend records permission decisions in Firewall Logs. Your request is processed by the configured TrustGate backend.</p></form></section></div>;
}
