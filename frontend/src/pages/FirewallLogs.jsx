import { useCallback, useEffect, useMemo, useState } from "react";
import { Search, Download, ScrollText, RefreshCw } from "lucide-react";
import PageHeader from "../components/PageHeader";
import StatusPill from "../components/StatusPill";
import { getBackendEvents } from "../services/api";

function csvCell(value) {
  return `"${String(value ?? "").replaceAll('"', '""')}"`;
}

export default function FirewallLogs() {
  const [events, setEvents] = useState([]);
  const [query, setQuery] = useState("");
  const [decision, setDecision] = useState("ALL");
  const [risk, setRisk] = useState("ALL");
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");

  const loadEvents = useCallback(async () => {
    setLoading(true);
    setError("");
    try {
      setEvents(await getBackendEvents());
    } catch (requestError) {
      setError(requestError.message);
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => { loadEvents(); }, [loadEvents]);

  const rows = useMemo(() => events
    .filter((event) => `${event.id} ${event.type} ${event.source} ${event.risk} ${event.decision} ${event.promptPreview || ""}`.toLowerCase().includes(query.toLowerCase()))
    .filter((event) => decision === "ALL" || event.decision === decision)
    .filter((event) => risk === "ALL" || event.risk === risk), [events, query, decision, risk]);

  function exportCSV() {
    const columns = ["id", "type", "source", "risk", "risk_score", "decision", "timestamp", "promptPreview"];
    const csv = [columns.join(","), ...rows.map((event) => columns.map((column) => csvCell(event[column])).join(","))].join("\n");
    const url = URL.createObjectURL(new Blob(["\ufeff" + csv], { type: "text/csv;charset=utf-8;" }));
    const anchor = document.createElement("a");
    anchor.href = url;
    anchor.download = "trustgate-firewall-logs.csv";
    anchor.click();
    URL.revokeObjectURL(url);
  }

  const count = (value) => events.filter((event) => event.decision === value).length;
  return <div>
    <PageHeader eyebrow="SECURITY CENTER" title="Firewall Logs" description="Search and review security events generated by scans and chat requests." action={<button onClick={exportCSV} disabled={!rows.length} className="accent-bg flex items-center gap-2 rounded-xl px-3 py-2 text-[11px] font-semibold disabled:opacity-40"><Download size={14}/> Export CSV</button>}/>
    {error && <p role="alert" className="mb-4 rounded-lg border border-red-500/30 bg-red-500/10 p-3 text-xs text-red-400">Could not load backend events: {error}</p>}
    <div className="mb-5 grid gap-3 sm:grid-cols-3">{[["All events", events.length], ["Blocked", count("BLOCK")], ["Needs review", count("REVIEW")]].map(([label, value]) => <div key={label} className="panel p-4"><p className="text-[11px] text-muted">{label}</p><p className="mt-2 text-2xl font-bold text-main">{loading ? "—" : value}</p></div>)}</div>
    <section className="panel p-5">
      <div className="mb-5 flex flex-col justify-between gap-3 md:flex-row md:items-center"><div className="flex items-center gap-2"><ScrollText size={18} className="accent-text"/><div><h3 className="text-sm font-semibold text-main">Event history</h3><p className="text-[10px] text-muted">{loading ? "Loading backend events…" : `${events.length} backend events`}</p></div></div><button onClick={loadEvents} disabled={loading} className="panel-soft flex items-center gap-2 self-start rounded-lg px-3 py-2 text-[10px] text-muted disabled:opacity-40"><RefreshCw size={13} className={loading ? "animate-spin" : ""}/> Refresh</button></div>
      <div className="mb-5 grid gap-2 md:grid-cols-[1fr_170px_170px]"><div className="input-ui flex items-center gap-2 rounded-xl px-3"><Search size={15} className="text-muted"/><input value={query} onChange={(event) => setQuery(event.target.value)} placeholder="Search event, source or prompt…" className="w-full bg-transparent py-3 text-xs outline-none placeholder:text-subtle"/></div><select value={decision} onChange={(event) => setDecision(event.target.value)} className="input-ui rounded-xl px-3 py-3 text-xs"><option value="ALL">All decisions</option><option>ALLOW</option><option>WARNING</option><option>REVIEW</option><option>BLOCK</option></select><select value={risk} onChange={(event) => setRisk(event.target.value)} className="input-ui rounded-xl px-3 py-3 text-xs"><option value="ALL">All risk levels</option><option>LOW</option><option>MEDIUM</option><option>HIGH</option><option>CRITICAL</option></select></div>
      <div className="overflow-x-auto"><table className="w-full min-w-[760px] text-left"><thead><tr className="border-b border-ui text-[10px] uppercase tracking-wider text-subtle"><th className="pb-3">Event ID</th><th className="pb-3">Threat / Event</th><th className="pb-3">Source</th><th className="pb-3">Risk</th><th className="pb-3">Decision</th><th className="pb-3">Timestamp</th></tr></thead><tbody>{rows.map((event) => <tr key={event.id} className="border-b border-ui last:border-0"><td className="py-4 text-xs font-semibold text-main">{event.id}</td><td className="py-4 text-xs text-muted">{event.type}{event.promptPreview && <p className="mt-1 max-w-[220px] truncate text-[9px] text-subtle">{event.promptPreview}</p>}</td><td className="py-4 text-xs text-muted">{event.source}</td><td className="py-4"><StatusPill value={event.risk}/></td><td className="py-4"><StatusPill value={event.decision}/></td><td className="py-4 text-[10px] text-muted">{event.timestamp ? new Date(event.timestamp).toLocaleString() : "—"}</td></tr>)}</tbody></table>
        {loading && <p className="py-10 text-center text-xs text-muted">Loading backend events…</p>}
        {!loading && !error && rows.length === 0 && <p className="py-10 text-center text-xs text-muted">No backend events match these filters.</p>}
      </div>
      <p className="mt-4 text-[10px] text-subtle">Event history is provided by GET /api/security/events.</p>
    </section>
  </div>;
}
